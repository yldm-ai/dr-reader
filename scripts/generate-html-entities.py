"""Generate HTML5 named-character data independently of calibre (Python PSF License)."""
from html.entities import html5
from pathlib import Path

root = Path(__file__).resolve().parent.parent
xml_names = {"amp", "lt", "gt", "quot", "apos"}
entries = []
for name, text in sorted(html5.items()):
    if not name.endswith(";") or name[:-1] in xml_names:
        continue
    numeric = "".join(f"&#x{ord(char):X};" for char in text)
    entries.append(f'    {{"{name[:-1]}", "{numeric}"}},')
header = "// Generated by scripts/generate-html-entities.py from Python html.entities.html5.\n// Standard HTML5 named character references; Python PSF License: licenses/python-html-entities.txt.\n"
(root / "engine/src/html-entities.inc").write_text(header + "\n".join(entries) + "\n", encoding="utf-8")
