// Regenerates web/material-icons.ts from the pinned @material-symbols/svg-400 package.
// Only the listed Rounded symbols are inlined, so the app ships a few KB of path data,
// needs no icon font or network access, and Node-side tests can import the module.
// Usage: node scripts/material-icons.ts
import { readFile, writeFile } from 'node:fs/promises';
import { resolve } from 'node:path';

const symbols = [
  'add', 'arrow_back', 'arrow_forward', 'arrow_upward', 'auto_stories', 'bookmark', 'bookmark-fill',
  'chat_bubble', 'check', 'chevron_right', 'close', 'content_copy', 'cookie', 'crop_portrait', 'delete', 'dictionary', 'domino_mask', 'draft', 'forum', 'edit', 'edit_note',
  'format_align_center', 'format_align_justify', 'format_align_left', 'format_underlined',
  'fullscreen', 'fullscreen_exit', 'grid_view', 'info', 'ink_highlighter', 'keep', 'keyboard_arrow_down', 'keyboard_double_arrow_down', 'keyboard_double_arrow_up', 'library_books',
  'menu_book', 'menu_open', 'palette', 'person', 'play_arrow', 'refresh', 'remove', 'schedule', 'search', 'settings', 'smart_toy', 'speaker_notes_off', 'stop', 'text_fields',
  'tune', 'two_pager', 'view_day', 'view_list',
];
const root = resolve('node_modules/@material-symbols/svg-400/rounded');
const { version } = JSON.parse(await readFile(resolve('node_modules/@material-symbols/svg-400/package.json'), 'utf8'));
const entries = [];
for (const name of symbols) {
  const svg = await readFile(resolve(root, `${name}.svg`), 'utf8');
  const paths = [...svg.matchAll(/<path d="([^"]+)"/g)].map(match => match[1]);
  if (!svg.includes('viewBox="0 -960 960 960"') || paths.length !== 1)
    throw new Error(`${name}: expected one path in the 960-unit Material Symbols grid`);
  entries.push(`  '${name}': '${paths[0]}',`);
}
await writeFile(resolve('web/material-icons.ts'), `// Generated by scripts/material-icons.ts from @material-symbols/svg-400 ${version}
// (Material Symbols Rounded, weight 400, Apache-2.0). Do not edit by hand.
export const materialPaths: Record<string, string> = {
${entries.join('\n')}
};
`);
console.log(`wrote ${symbols.length} Material Symbols Rounded paths`);
